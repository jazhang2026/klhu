// Generates the bundled language-ID profiles for `lib/langid/langid.dart`
// (spec 034 US3) from `tool/langid_corpus/{en,es,zh-Hans}.txt`.
//
//   dart run tool/gen_langid_profiles.dart
//
// Character n-grams (1..4) over whitespace-normalized, lowercased text.
// N-grams seen fewer than [_minCount] times are pruned — they carry noise,
// not signal, and dropping them keeps the shipped profile small. Scores are
// log10 probabilities scaled by 1000 and stored as ints; an unseen n-gram
// scores the per-(language, n) floor emitted alongside.
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;

const _minN = 1;
const _maxN = 4;
const _alpha = 0.01; // add-α smoothing

/// Per-language pruning. Only Latin-script languages are modelled: CJK text
/// is decided by `detectLanguage`'s ideograph rule before the model runs, so
/// a zh profile would be dead weight (and its n-gram space is huge).
const _profileParams = <String, ({int minCount, int maxN})>{
  'en': (minCount: 8, maxN: 4),
  'es': (minCount: 8, maxN: 4),
};

String normalize(String text) =>
    text.toLowerCase().replaceAll(RegExp(r'\s+'), ' ').trim();

/// Dart-string literal for an n-gram key: JSON quoting plus the `$` escape
/// JSON doesn't know about.
String dartKey(String key) =>
    jsonEncode(key).replaceAll(r'$', r'\$');

int scaledLog10(double p) => (math.log(p) / math.ln10 * 1000).round();

void main() {
  final out = File('lib/langid/profiles_data.dart');
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_langid_profiles.dart — do not edit.')
    ..writeln('// Char n-gram ($_minN-$_maxN) log-probability profiles for the')
    ..writeln('// Latin-script languages; zh-Hans is decided by the CJK rule.')
    ..writeln('// trained on tool/langid_corpus (Tatoeba, CC-BY 2.0 FR).')
    ..writeln('const kLangIdProfiles = <String, Map<int, Map<String, int>>>{');

  final floors = StringBuffer("const kLangIdFloors = <String, Map<int, int>>{");
  for (final lang in const ['en', 'es']) {
    final params = _profileParams[lang]!;
    final minCount = params.minCount;
    final maxN = params.maxN;
    final counts = <int, Map<String, int>>{
      for (var n = _minN; n <= maxN; n++) n: {},
    };
    final file = File('tool/langid_corpus/$lang.txt');
    var total = 0;
    for (final line in file.readAsLinesSync()) {
      if (line.startsWith('#')) continue;
      final text = ' ${normalize(line)} ';
      for (var n = _minN; n <= maxN; n++) {
        final grams = counts[n]!;
        for (var i = 0; i + n <= text.length; i++) {
          final gram = text.substring(i, i + n);
          grams[gram] = (grams[gram] ?? 0) + 1;
        }
      }
      total += text.length;
    }

    buffer.writeln("  '$lang': {");
    floors.write("  '$lang': {");
    for (var n = _minN; n <= maxN; n++) {
      final grams = counts[n]!
          .entries
          .where((e) => e.value >= minCount)
          .toList()
          ..sort((a, b) => b.value.compareTo(a.value));
      final denom = total + _alpha * grams.length;
      final floor = scaledLog10(_alpha / denom);
      floors.write('    $n: $floor,');
      buffer.writeln('    $n: {');
      for (final e in grams) {
        buffer.writeln(
            '      ${dartKey(e.key)}: ${scaledLog10((e.value + _alpha) / denom)},');
      }
      buffer.writeln('    },');
    }
    floors.write('  },');
    buffer.writeln('  },');
    final kept = counts.values.fold<int>(0, (a, m) => a + m.length);
    stderr.writeln('$lang: profiles written ($kept raw n-gram kinds)');
  }
  floors.writeln('};');
  buffer.writeln('};');
  out.createSync(recursive: true);
  out.writeAsStringSync('$floors\n$buffer');
  stderr.writeln('wrote ${out.path} (${out.lengthSync()} bytes)');
}
